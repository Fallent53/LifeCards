function tableExists(db,name){
  return Boolean(
    db.prepare("SELECT name FROM sqlite_master WHERE type='table' AND name=?").get(String(name))
  );
}

function taxonomyMeta(key){
  if(!tableExists(taxonomy,"meta"))return null;
  return taxonomy.prepare("SELECT value FROM meta WHERE key=?").get(String(key))?.value??null;
}

