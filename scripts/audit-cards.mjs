function classify(row,knowledge){
  if(knowledge?.auditTransientError){
    return {status:"ERROR",reason:knowledge.auditTransientError};
  }

  const scientific=String(row.scientific_name||"").trim();
  const rank=String(row.rank||"").trim();
  if(!scientific||!rank){
    return {status:"BAD_DATA",reason:"missing scientific name or rank"};
  }

  const media=knowledge?.media||null;
  if(!media?.imageUrl){
    return {status:"NO_IMAGE",reason:"no usable image resolved"};
  }

  const match=String(media.mediaMatch||"").toUpperCase();
  const confidence=String(media.confidence||"LOW").toUpperCase();
  const representative=match.includes("REPRESENTATIVE")||match.includes("DESCENDANT");

  return {
    status:"READY",
    reason:representative
      ?"coverage-first representative image accepted for prototype"
      :`coverage-first image accepted (${media.resolver||"unknown resolver"} / ${confidence})`,
  };
}

function cleanAuditQuery(row){
  const rank=String(row.rank||"").toLowerCase().trim();
  let value=String(row.canonical_name||row.scientific_name||"").trim();
  const authorship=String(row.authorship||"").trim();

  if(authorship&&value.toLowerCase().endsWith(authorship.toLowerCase())){
    value=value.slice(0,value.length-authorship.length).trim();
  }

  const authorish=/\b\d{4}\b|\bemend\.?\b|\bsensu\b|\bex\b|\bet al\.?\b|\bCavalier-Smith\b/i;
  if(authorish.test(value)){
    if(["species","subspecies","variety","subvariety","form","subform"].includes(rank)){
      const match=value.match(/^([A-ZÀ-ÖØ-Þ][\p{L}.-]+\s+[a-z][\p{L}.-]+(?:\s+[a-z][\p{L}.-]+)?)/u);
      if(match)value=match[1];
    }else{
      value=value.split(/\s+/)[0];
    }
  }

  return value||String(row.scientific_name||"").trim();
}

let processed=0;
const runStarted=Date.now();
const auditBatchSize=Math.max(10,Math.min(50,Number(args.get("batch-size")||40)));

for(let offset=0;offset<rows.length;offset+=auditBatchSize){
  const chunk=rows.slice(offset,offset+auditBatchSize);
  const entries=chunk.map((row)=>({
    id:String(row.id),
    query:cleanAuditQuery(row),
    rank:String(row.rank||""),
    extinct:Boolean(row.extinct),
  }));

  const resolved={};
  const missingEntries=[];

  for(const entry of entries){
    const row=chunk.find((candidate)=>String(candidate.id)===entry.id);
    const cached=cachedMediaByTaxon.get(entry.id,entry.query,entry.id);
    if(cached?.image_url){
      resolved[entry.id]={
        query:entry.query,
        media:{
          imageUrl:cached.image_url,
          originalUrl:cached.source_url||cached.image_url,
          source:cached.provider||"LifeCards local media index",
          resolver:cached.resolver||"local-media-index",
          confidence:cached.confidence||"MEDIUM",
          creator:cached.creator||null,
          license:cached.license||null,
          mediaMatch:cached.exactness||null,
          providerTaxonId:cached.provider_taxon_id||null,
          cached:true,
        },
        sourceStatus:{media:"cached"},
      };
    }else{
      missingEntries.push(entry);
    }
  }

  if(missingEntries.length){
    try{
      Object.assign(resolved,await getCoverageMediaBatch(missingEntries));
    }catch{
      // Individual rows remain NO_IMAGE/ERROR; cached rows are still usable.
    }
  }

  for(const row of chunk){
    const knowledge=resolved[String(row.id)]||null;
    const classification=classify(row,knowledge);
    const media=knowledge?.media||null;

    if(media?.imageUrl){
      const confidence=String(media.confidence||"LOW").toUpperCase();
      const match=String(media.mediaMatch||"");
      const score=
        (confidence==="HIGH"?100:confidence==="MEDIUM"?70:40)+
        (/EXACT/i.test(match)?30:/REPRESENTATIVE|DESCENDANT/i.test(match)?10:0);

      mediaIndexUpsert.run(
        String(row.id),
        row.scientific_name,
        cleanAuditQuery(row).toLowerCase(),
        media.source||null,
        media.providerTaxonId||media.inaturalistTaxonId||media.occurrenceKey||null,
        media.imageUrl,
        media.imageUrl,
        media.originalUrl||knowledge?.wikipedia?.pageUrl||null,
        "image",
        match||null,
        score,
        media.resolver||null,
        media.confidence||null,
        media.creator||null,
        media.license||null,
        Date.now()
      );
    }

    upsert.run(
      String(row.id),
      row.scientific_name,
      row.common_name||row.canonical_name||row.scientific_name,
      row.rank||"",
      row.rarity||"",
      classification.status,
      classification.reason,
      media?.imageUrl||null,
      media?.source||null,
      media?.resolver||null,
      media?.confidence||null,
      media?.creator||null,
      media?.license||null,
      knowledge?.wikipedia?.pageUrl||null,
      knowledge?.wikidata?.id||null,
      knowledge?.taxonomy?.ncbiTaxId||null,
      AUDIT_RESOLVER_VERSION,
      Date.now()
    );

    processed+=1;
    console.log(
      `[${processed}/${rows.length}] ${classification.status.padEnd(8)} · ${cleanAuditQuery(row)} · ${media?.resolver||"no-media"} · ${classification.reason}`
    );
  }

  if(offset+auditBatchSize<rows.length){
    await new Promise((resolve)=>setTimeout(resolve,350));
  }
}

